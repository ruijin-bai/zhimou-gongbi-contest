def cpm(durs: dict[str, float] | None = None) -> dict[str, dict]:
    """前推后推：返回 {code: {es, ef, ls, lf, tf}}（天，相对开工日）。durs 可覆盖工期（用于更新期的剩余工期）。"""
    d = {p[0]: (durs or {}).get(p[0], p[3]) for p in PLAN}
    es, ef = {}, {}
    for code, *_x, preds in PLAN:
        s = 0.0
        for pc, kind, lag in preds:
            if kind == "FS":
                s = max(s, ef[pc] + lag)
            elif kind == "SS":
                s = max(s, es[pc] + lag)
            elif kind == "FF":
                s = max(s, ef[pc] + lag - d[code])
        es[code], ef[code] = s, s + d[code]
    end = max(ef.values())
    succ: dict[str, list] = {}
    for code, *_x, preds in PLAN:
        for pc, kind, lag in preds:
            succ.setdefault(pc, []).append((code, kind, lag))
    ls, lf = {}, {}
    for code, *_x, preds in reversed(PLAN):
        f = end
        for sc, kind, lag in succ.get(code, []):
            if kind == "FS":
                f = min(f, ls[sc] - lag)
            elif kind == "SS":
                f = min(f, ls[sc] - lag + d[code])
            elif kind == "FF":
                f = min(f, lf[sc] - lag)
        lf[code], ls[code] = f, f - d[code]
    return {c: {"es": es[c], "ef": ef[c], "ls": ls[c], "lf": lf[c], "tf": round(ls[c] - es[c], 1)} for c in es}


