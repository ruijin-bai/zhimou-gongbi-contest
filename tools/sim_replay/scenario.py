def daily_truth() -> dict[str, dict[str, list[DayWork]]]:
    """{日期: {技术员: [DayWork…]}}；桩基按“浇筑完成的根数”整数累计。"""
    rng = random.Random(SEED)
    out: dict[str, dict[str, list[DayWork]]] = {}
    frac: dict[str, float] = {}   # 按“根/个/m”计量的作业整数累计（首日即可计 1）
    done = {p[0]: 0.0 for p in PLAN}
    d = START
    while d <= END:
        day: dict[str, list[DayWork]] = {t: [] for t in TECHS}
        for code, name, wbs, dur, qty, unit, price, owner, preds in PLAN:
            if owner not in TECHS or not dur:
                continue
            q, note = _rate(code, d, rng)
            if unit in ("根", "个", "m") and q > 0:
                a = frac.get(code, 0.35)
                frac[code] = a + q
                q = float(int(a + q) - int(a))
            q = min(q, qty - done[code])
            if q > 0 or note:
                done[code] += max(q, 0)
                day[owner].append(DayWork(code, round(q, 2), note))
        out[d.isoformat()] = day
        d += timedelta(days=1)
    return out


def cumulative(truth: dict, upto: date) -> dict[str, float]:
    acc = {p[0]: 0.0 for p in PLAN}
    for k, day in truth.items():
        if k <= upto.isoformat():
            for works in day.values():
                for w in works:
                    acc[w.code] += w.qty
    return acc


